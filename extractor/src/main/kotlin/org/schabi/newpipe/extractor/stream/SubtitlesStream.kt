package org.schabi.newpipe.extractor.stream

import org.schabi.newpipe.extractor.MediaFormat
import org.schabi.newpipe.extractor.exceptions.ParsingException
import org.schabi.newpipe.extractor.services.youtube.ItagItem
import org.schabi.newpipe.extractor.utils.LocaleCompat
import java.util.Locale

/**
 * A subtitles stream, created with a [Builder].
 *
 * @param id             the identifier which uniquely identifies the stream, e.g. for YouTube
 *                       this would be the itag
 * @param content        the content or the URL of the stream, depending on whether isUrl is
 *                       true
 * @param isUrl          whether content is the URL or the actual content of e.g. a DASH
 *                       manifest
 * @param mediaFormat    the [MediaFormat] used by the stream
 * @param deliveryMethod the [DeliveryMethod] of the stream
 * @param languageCode   the language code of the stream
 * @param name           the service-provided display name of the stream (may be `null`)
 * @param isAutoGenerated whether the subtitles are auto-generated by the streaming service
 * @param manifestUrl    the URL of the manifest this stream comes from (if applicable,
 *                       otherwise null)
 */
public class SubtitlesStream @Throws(ParsingException::class) private constructor(
    id: String,
    content: String,
    isUrl: Boolean,
    mediaFormat: MediaFormat?,
    deliveryMethod: DeliveryMethod,
    languageCode: String,
    /**
     * The service-provided display name of the subtitles, if the service exposed one.
     *
     * This is useful when a video has multiple tracks that share the same language code (for
     * example two "en" tracks). The service's own name field is the only reliable way to tell
     * such tracks apart in a picker.
     *
     * `null` if the service does not expose one.
     */
    public val name: String?,
    /**
     * Whether the subtitles are auto-generated.
     *
     * Some streaming services can generate subtitles for their contents, like YouTube.
     */
    public val isAutoGenerated: Boolean,
    manifestUrl: String?,
) : Stream(id, content, isUrl, mediaFormat, deliveryMethod, manifestUrl) {

    /**
     * The [locale][Locale] of the subtitles.
     *
     * The language code comes from the service, so the error message does not quote it.
     */
    public val locale: Locale = LocaleCompat.forLanguageTag(languageCode).orElse(null)
        ?: throw ParsingException("Not a valid locale language code")

    /**
     * The language tag of the subtitles.
     */
    public val languageTag: String = languageCode

    /**
     * The extension of the subtitles, or `null` when the media format is unknown (this threw a
     * `NullPointerException` before).
     */
    public val extension: String?
        get() = format?.suffix

    /**
     * The display language name of the subtitles.
     */
    public val displayLanguageName: String
        get() = locale.getDisplayName(locale)

    /**
     * No subtitles which are currently extracted use an [ItagItem], so `null` is
     * returned by this method.
     */
    override val itagItem: ItagItem?
        get() = null

    /**
     * Class to build [SubtitlesStream] objects.
     *
     * Create a new [Builder] instance with default values.
     */
    public class Builder {
        private var id: String? = null
        private var content: String? = null
        private var isUrl = false
        private var deliveryMethod: DeliveryMethod? = DeliveryMethod.PROGRESSIVE_HTTP
        private var mediaFormat: MediaFormat? = null
        private var manifestUrl: String? = null
        private var languageCode: String? = null
        private var name: String? = null

        // Nullable instead of the primitive type, to check that the setter has been called
        private var autoGenerated: Boolean? = null

        /**
         * Set the identifier of the [SubtitlesStream].
         *
         * @param id the identifier of the [SubtitlesStream], which should not be null
         * (otherwise the fallback to create the identifier will be used when building
         * the builder)
         * @return this [Builder] instance
         */
        public fun setId(id: String?): Builder = apply { this.id = id }

        /**
         * Set the content of the [SubtitlesStream].
         *
         * It must not be null, and should be non empty.
         *
         * @param content the content of the [SubtitlesStream], which must not be null
         * @param isUrl   whether the content is a URL
         * @return this [Builder] instance
         */
        public fun setContent(content: String?, isUrl: Boolean): Builder = apply {
            this.content = content
            this.isUrl = isUrl
        }

        /**
         * Set the [MediaFormat] used by the [SubtitlesStream].
         *
         * It should be one of the subtitles [MediaFormat]s ([SRT][MediaFormat.SRT],
         * [TRANSCRIPT1][MediaFormat.TRANSCRIPT1], [TRANSCRIPT2][MediaFormat.TRANSCRIPT2],
         * [TRANSCRIPT3][MediaFormat.TRANSCRIPT3], [TTML][MediaFormat.TTML], or
         * [VTT][MediaFormat.VTT]) but can be `null` if the media format could
         * not be determined.
         *
         * The default value is `null`.
         *
         * @param mediaFormat the [MediaFormat] of the [SubtitlesStream], which can be
         * null
         * @return this [Builder] instance
         */
        public fun setMediaFormat(mediaFormat: MediaFormat?): Builder =
            apply { this.mediaFormat = mediaFormat }

        /**
         * Set the [DeliveryMethod] of the [SubtitlesStream].
         *
         * It must not be null.
         *
         * The default delivery method is [DeliveryMethod.PROGRESSIVE_HTTP].
         *
         * @param deliveryMethod the [DeliveryMethod] of the [SubtitlesStream], which
         * must not be null
         * @return this [Builder] instance
         */
        public fun setDeliveryMethod(deliveryMethod: DeliveryMethod?): Builder =
            apply { this.deliveryMethod = deliveryMethod }

        /**
         * Sets the URL of the manifest this stream comes from (if applicable, otherwise null).
         *
         * @param manifestUrl the URL of the manifest this stream comes from or `null`
         * @return this [Builder] instance
         */
        public fun setManifestUrl(manifestUrl: String?): Builder =
            apply { this.manifestUrl = manifestUrl }

        /**
         * Set the language code of the [SubtitlesStream].
         *
         * It **must not be null** and should not be an empty string.
         *
         * @param languageCode the language code of the [SubtitlesStream]
         * @return this [Builder] instance
         */
        public fun setLanguageCode(languageCode: String?): Builder =
            apply { this.languageCode = languageCode }

        /**
         * Set the display name of the [SubtitlesStream] as provided by the streaming
         * service.
         *
         * Some services (e.g. YouTube) ship a user-facing track label alongside the language code,
         * which is useful when a video has multiple tracks that share the same language code (e.g.
         * two "en" tracks with different track names). When present, consumers should prefer this
         * over the locale-derived display name so the two tracks can be told apart in a picker.
         *
         * May be `null` if the service does not expose a track name.
         *
         * @param name the display name of the stream, or `null`
         * @return this [Builder] instance
         */
        public fun setName(name: String?): Builder = apply { this.name = name }

        /**
         * Set whether the subtitles have been auto-generated by the streaming service.
         *
         * @param autoGenerated whether the subtitles have been generated by the streaming
         * service
         * @return this [Builder] instance
         */
        public fun setAutoGenerated(autoGenerated: Boolean): Builder =
            apply { this.autoGenerated = autoGenerated }

        /**
         * Build a [SubtitlesStream] using the builder's current values.
         *
         * The content (and so the `isUrl` boolean), the language code and the
         * `isAutoGenerated` properties must have been set.
         *
         * If no identifier has been set, an identifier will be generated using the language code
         * and the media format suffix, if the media format is known.
         *
         * The error messages never quote the content, which is usually a stream URL.
         *
         * @return a new [SubtitlesStream] using the builder's current values
         * @throws IllegalStateException if `id`, `content` (and so `isUrl`),
         * `deliveryMethod`, `languageCode` or the `isAutogenerated` have been
         * not set, or have been set as `null`
         * @throws ParsingException if the language code is not a valid locale
         */
        @Throws(ParsingException::class)
        public fun build(): SubtitlesStream {
            val content = checkNotNull(content) {
                "No valid content was specified. Please specify a valid one with setContent."
            }
            val deliveryMethod = checkNotNull(deliveryMethod) {
                "The delivery method of the subtitles stream has been set as null, which " +
                    "is not allowed. Pass a valid one instead with" +
                    "setDeliveryMethod."
            }
            val languageCode = checkNotNull(languageCode) {
                "The language code of the subtitles stream has " +
                    "been not set or is null. Make sure you specified an non null language " +
                    "code with setLanguageCode."
            }
            val autoGenerated = checkNotNull(autoGenerated) {
                "The subtitles stream has been not set as an " +
                    "autogenerated subtitles stream or not. Please specify this information " +
                    "with setIsAutoGenerated."
            }
            // Like before, a generated identifier is kept by the builder
            val id = id ?: (languageCode + (mediaFormat?.let { "." + it.suffix } ?: ""))
                .also { this.id = it }
            return SubtitlesStream(
                id, content, isUrl, mediaFormat, deliveryMethod,
                languageCode, name, autoGenerated, manifestUrl,
            )
        }
    }

    /**
     * Whether the stats of [other] equal this stream's, including the language and whether
     * both are auto-generated.
     */
    override fun equalStats(other: Stream?): Boolean = super.equalStats(other) &&
        other is SubtitlesStream &&
        languageTag == other.languageTag &&
        isAutoGenerated == other.isAutoGenerated

    private companion object {
        private const val serialVersionUID: Long = 1L
    }
}
