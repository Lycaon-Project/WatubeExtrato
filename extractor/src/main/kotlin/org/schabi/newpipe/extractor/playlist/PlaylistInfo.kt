package org.schabi.newpipe.extractor.playlist

import org.schabi.newpipe.extractor.Image
import org.schabi.newpipe.extractor.ListExtractor.InfoItemsPage
import org.schabi.newpipe.extractor.ListInfo
import org.schabi.newpipe.extractor.NewPipe
import org.schabi.newpipe.extractor.Page
import org.schabi.newpipe.extractor.StreamingService
import org.schabi.newpipe.extractor.exceptions.ExtractionException
import org.schabi.newpipe.extractor.exceptions.ParsingException
import org.schabi.newpipe.extractor.linkhandler.ListLinkHandler
import org.schabi.newpipe.extractor.stream.Description
import org.schabi.newpipe.extractor.stream.StreamInfoItem
import org.schabi.newpipe.extractor.utils.ExtractorHelper
import java.io.IOException

public class PlaylistInfo @Throws(ParsingException::class) private constructor(
    serviceId: Int,
    linkHandler: ListLinkHandler,
    name: String,
) : ListInfo<StreamInfoItem>(serviceId, linkHandler, name) {

    /**
     * Mixes are handled as particular playlists in NewPipeExtractor. [PlaylistType.NORMAL] is
     * for non-mixes, while other values are for the different types of mixes. The type of a mix
     * depends on how its contents are autogenerated.
     */
    public enum class PlaylistType {
        /**
         * A normal playlist (not a mix)
         */
        NORMAL,

        /**
         * A mix made only of streams related to a particular stream, for example YouTube mixes
         */
        MIX_STREAM,

        /**
         * A mix made only of music streams related to a particular stream, for example YouTube
         * music mixes
         */
        MIX_MUSIC,

        /**
         * A mix made only of streams related to a particular (musical) genre, for example YouTube
         * genre mixes
         */
        MIX_GENRE,
    }

    public var uploaderUrl: String = ""
    public var uploaderName: String = ""
    public var subChannelUrl: String? = null
    public var subChannelName: String? = null

    /** The description, [Description.EMPTY_DESCRIPTION] (instead of `null`) when unknown. */
    public var description: Description = Description.EMPTY_DESCRIPTION
    public var banners: List<Image> = emptyList()
    public var subChannelAvatars: List<Image> = emptyList()
    public var thumbnails: List<Image> = emptyList()
    public var uploaderAvatars: List<Image> = emptyList()
    public var streamCount: Long = 0
    public var playlistType: PlaylistType? = null

    public companion object {
        private const val serialVersionUID: Long = 1L

        /** Below this count of uploader failures, a playlist may just have no uploader. */
        private const val UPLOADER_FIELDS_WITHOUT_ERROR = 3

        @JvmStatic
        @Throws(IOException::class, ExtractionException::class)
        public fun getInfo(url: String): PlaylistInfo = getInfo(NewPipe.getServiceByUrl(url), url)

        @JvmStatic
        @Throws(IOException::class, ExtractionException::class)
        public fun getInfo(service: StreamingService, url: String): PlaylistInfo {
            val extractor = service.getPlaylistExtractor(url)
            extractor.fetchPage()
            return getInfo(extractor)
        }

        @JvmStatic
        @Throws(IOException::class, ExtractionException::class)
        public fun getMoreItems(
            service: StreamingService,
            url: String,
            page: Page,
        ): InfoItemsPage<StreamInfoItem> = service.getPlaylistExtractor(url).getPage(page)

        /**
         * Get PlaylistInfo from PlaylistExtractor
         *
         * @param extractor an extractor where fetchPage() was already got called on.
         */
        @JvmStatic
        @Throws(ExtractionException::class)
        public fun getInfo(extractor: PlaylistExtractor): PlaylistInfo {
            val info = PlaylistInfo(extractor.serviceId, extractor.linkHandler, extractor.name)
            // collect uploader extraction failures until we are sure this is not
            // just a playlist without an uploader
            val uploaderParsingErrors = ArrayList<Throwable>(UPLOADER_FIELDS_WITHOUT_ERROR * 2)

            optional(info, info::addError) { originalUrl = extractor.originalUrl }
            optional(info, info::addError) { streamCount = extractor.streamCount }
            optional(info, info::addError) { description = extractor.description }
            optional(info, info::addError) { thumbnails = extractor.thumbnails }
            optional(info, uploaderParsingErrors::add) { uploaderUrl = extractor.uploaderUrl }
            optional(info, uploaderParsingErrors::add) { uploaderName = extractor.uploaderName }
            optional(info, uploaderParsingErrors::add) {
                uploaderAvatars = extractor.uploaderAvatars
            }
            optional(info, uploaderParsingErrors::add) { subChannelUrl = extractor.subChannelUrl }
            optional(info, uploaderParsingErrors::add) {
                subChannelName = extractor.subChannelName
            }
            optional(info, uploaderParsingErrors::add) {
                subChannelAvatars = extractor.subChannelAvatars
            }
            optional(info, info::addError) { banners = extractor.banners }
            optional(info, info::addError) { playlistType = extractor.playlistType }

            // do not fail if everything but the uploader infos could be collected (TODO better
            // comment)
            if (uploaderParsingErrors.isNotEmpty() &&
                (info.errors.isNotEmpty() || uploaderParsingErrors.size < UPLOADER_FIELDS_WITHOUT_ERROR)
            ) {
                info.addAllErrors(uploaderParsingErrors)
            }

            val itemsPage: InfoItemsPage<StreamInfoItem> =
                ExtractorHelper.getItemsPageOrLogError(info, extractor)
            info.relatedItems = itemsPage.items
            info.nextPage = itemsPage.nextPage

            return info
        }

        /** Runs one optional extraction: a failure goes to [onError]. */
        private inline fun optional(
            info: PlaylistInfo,
            onError: (Throwable) -> Unit,
            block: PlaylistInfo.() -> Unit,
        ) {
            try {
                info.block()
            } catch (e: Exception) {
                onError(e)
            }
        }
    }
}
