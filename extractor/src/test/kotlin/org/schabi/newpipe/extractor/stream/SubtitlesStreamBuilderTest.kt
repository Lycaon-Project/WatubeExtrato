package org.schabi.newpipe.extractor.stream

import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Assertions.assertNull
import org.junit.jupiter.api.Test
import org.schabi.newpipe.extractor.MediaFormat
import org.schabi.newpipe.extractor.exceptions.ParsingException

/**
 * Builder-level checks for the service-provided display name on [SubtitlesStream].
 * See TeamNewPipe/NewPipe#9218 — YouTube ships a user-facing name per caption track that
 * must survive the Builder → stream round-trip so downstream pickers can tell apart tracks
 * sharing a language code.
 */
internal class SubtitlesStreamBuilderTest {

    private fun validBuilder(): SubtitlesStream.Builder = SubtitlesStream.Builder()
        .setContent("https://example.com/sub.vtt", true)
        .setMediaFormat(MediaFormat.VTT)
        .setLanguageCode("en")
        .setAutoGenerated(false)

    @Test
    @Throws(ParsingException::class)
    fun nameRoundTripsThroughGetName() {
        val stream = validBuilder()
            .setName("English - CC1")
            .build()

        assertEquals("English - CC1", stream.name)
    }

    @Test
    @Throws(ParsingException::class)
    fun explicitNullNameIsAccepted() {
        val stream = validBuilder()
            .setName(null)
            .build()

        assertNull(stream.name)
    }

    @Test
    @Throws(ParsingException::class)
    fun nameDefaultsToNullWhenUnset() {
        // Existing extractors that do not call setName must keep working.
        val stream = validBuilder().build()

        assertNull(stream.name)
    }
}
