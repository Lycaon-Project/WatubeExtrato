package org.schabi.newpipe.timeago_generator

import org.schabi.newpipe.extractor.json.JsonObject
import org.schabi.newpipe.extractor.json.JsonParser
import java.io.File
import java.time.temporal.ChronoUnit

/**
 * Generates the Kotlin pattern holders of `timeago-parser` (one object per language, and the
 * `PatternMap` that finds them) from `timeago-parser/raw/unique_patterns.json`.
 *
 * Run from the root of the repository.
 */
object GeneratePatternClasses {

    private const val PATTERNS_DIR =
        "timeago-parser/src/main/kotlin/org/schabi/newpipe/extractor/timeago/patterns/"
    private const val PATTERN_MAP_FILE =
        "timeago-parser/src/main/kotlin/org/schabi/newpipe/extractor/timeago/PatternMap.kt"
    private const val MAX_LINE_LENGTH = 120
    private const val INDENT = "    "

    private val UNITS = listOf(
        "seconds" to ChronoUnit.SECONDS,
        "minutes" to ChronoUnit.MINUTES,
        "hours" to ChronoUnit.HOURS,
        "days" to ChronoUnit.DAYS,
        "weeks" to ChronoUnit.WEEKS,
        "months" to ChronoUnit.MONTHS,
        "years" to ChronoUnit.YEARS,
    )

    /** Kotlin hard keywords, which a language code can only be as a backquoted name. */
    private val KOTLIN_KEYWORDS = setOf(
        "as", "break", "class", "continue", "do", "else", "false", "for", "fun", "if", "in",
        "interface", "is", "null", "object", "package", "return", "super", "this", "throw",
        "true", "try", "typealias", "typeof", "val", "var", "when", "while",
    )

    private const val INFO_CLASS_GENERATED = "// DO NOT MODIFY THIS FILE MANUALLY\n" +
        "// This file was automatically generated by \"GeneratePatternClasses.kt\",\n" +
        "// modify the \"unique_patterns.json\" and re-generate instead.\n"

    private val LANGUAGE_CODE = Regex("[A-Za-z0-9_]+")

    @JvmStatic
    fun main(args: Array<String>) {
        val from = File("timeago-parser/raw/unique_patterns.json").inputStream().use {
            JsonParser.`object`().from(it)
        }
        val languageCodes = ArrayList<String>()

        for ((key, value) in from.toSortedMap()) {
            val languageCode = key.replace('-', '_')
            require(languageCode.matches(LANGUAGE_CODE)) { "Invalid language code: $key" }
            val unitsList = value as JsonObject

            println("Generating \"$languageCode\" pattern class...")
            File("$PATTERNS_DIR$languageCode.kt").writeText(patternClass(languageCode, unitsList))
            languageCodes.add(languageCode)
        }

        File(PATTERN_MAP_FILE).writeText(patternMap(languageCodes))
    }

    private fun patternClass(languageCode: String, unitsList: JsonObject): String {
        val wordSeparator = unitsList.getString("word_separator").orEmpty()
        val phrases = StringBuilder()
        val specialCases = StringBuilder()
        for ((unitName, unit) in UNITS) {
            val array = unitsList.getArray(unitName)
            phrases.append(phraseList(unitName, array.filterIsInstance<String>()))
            for (case in array.filterIsInstance<JsonObject>()) {
                for ((amount, text) in case) {
                    specialCases.append(INDENT).append(INDENT)
                        .append("putSpecialCase(ChronoUnit.").append(unit.name)
                        .append(", ").append(quote(text as String))
                        .append(", ").append(amount.toInt()).append(")\n")
                }
            }
        }

        val name = kotlinName(languageCode)
        return buildString {
            append(INFO_CLASS_GENERATED).append('\n')
            append("package org.schabi.newpipe.extractor.timeago.patterns\n\n")
            append("import org.schabi.newpipe.extractor.timeago.PatternsHolder\n")
            if (specialCases.isNotEmpty()) {
                append("import java.time.temporal.ChronoUnit\n")
            }
            append('\n')
            append("public object ").append(name).append(" : PatternsHolder(\n")
            append(INDENT).append("wordSeparator = ").append(quote(wordSeparator)).append(",\n")
            append(phrases)
            append(") {\n")
            if (specialCases.isNotEmpty()) {
                append(INDENT).append("init {\n")
                append(specialCases)
                append(INDENT).append("}\n\n")
            }
            append(INDENT).append("@JvmStatic\n")
            append(INDENT).append("public fun getInstance(): ").append(name).append(" = this\n")
            append("}\n")
        }
    }

    /** `name = listOf(...),` on one line when it fits, else one phrase per line. */
    private fun phraseList(unitName: String, phrases: List<String>): String {
        val quoted = phrases.map(::quote)
        val oneLine = "$INDENT$unitName = listOf(${quoted.joinToString(", ")}),\n"
        if (oneLine.codePointCount(0, oneLine.length) - 1 <= MAX_LINE_LENGTH) {
            return oneLine
        }
        return buildString {
            append(INDENT).append(unitName).append(" = listOf(\n")
            for (phrase in quoted) {
                append(INDENT).append(INDENT).append(phrase).append(",\n")
            }
            append(INDENT).append("),\n")
        }
    }

    private fun patternMap(languageCodes: List<String>): String = buildString {
        append(INFO_CLASS_GENERATED).append('\n')
        append("package org.schabi.newpipe.extractor.timeago\n\n")
        append("import org.schabi.newpipe.extractor.timeago.patterns.*\n\n")
        append("/**\n")
        append(" * The patterns of every supported language, by language code (with an optional\n")
        append(" * `_` and country code). A language's holder is only loaded when it is asked for.\n")
        append(" */\n")
        append("public object PatternMap {\n")
        append(INDENT).append("@JvmStatic\n")
        append(INDENT).append("public fun getPattern(languageCode: String): PatternsHolder? =")
            .append(" when (languageCode) {\n")
        for (languageCode in languageCodes) {
            append(INDENT).append(INDENT).append(quote(languageCode)).append(" -> ")
                .append(kotlinName(languageCode)).append('\n')
        }
        append(INDENT).append(INDENT).append("else -> null\n")
        append(INDENT).append("}\n")
        append("}\n")
    }

    private fun kotlinName(languageCode: String): String =
        if (languageCode in KOTLIN_KEYWORDS) "`$languageCode`" else languageCode

    /** [text] as a Kotlin string literal. */
    private fun quote(text: String): String = buildString {
        append('"')
        for (c in text) {
            when (c) {
                '"', '\\', '$' -> append('\\').append(c)
                '\n' -> append("\\n")
                else -> append(c)
            }
        }
        append('"')
    }
}
